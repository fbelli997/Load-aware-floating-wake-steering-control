function [T, x_disp, y_disp, x_dot, y_dot, theta, thetad, Faero] = ...
    DispActiveFloat_ss(T, tmpM, Sim, paramFLORIDyn, paramFLORIS, it, Ct)

%==========================================================================
% DispActiveFloat
%--------------------------------------------------------------------------
% ActiveFloat platform dynamics using a LINEAR 2-DOF state-space model
% (surge + pitch) with nonlinear external forcing.
%
% Structural dynamics:
%
%   M2*qddot + Beff2*qdot + Keff2*q = F2
%
% where:
%
%   q    = [surge; pitch]
%   qdot = [surge_rate; pitch_rate]
%
% State-space formulation:
%
%   x_dot = A*x + B*F(x)
%
% with:
%
%   x = [surge;
%        pitch;
%        surge_rate;
%        pitch_rate]
%
% Nonlinear forcing:
%
%   F2 = [Fs;
%         Mtheta]
%
% where aerodynamic thrust and hydrodynamic drag are recomputed at each
% integration sub-step.
%
% The matrices M, AddBLin, K and AddCLin already include:
%   - total mass + added mass
%   - radiation damping
%   - hydrostatic and linearized mooring restoring terms
%
% Nonlinear contributions are applied externally.
%
%==========================================================================


%% Current platform states

s      = T.floater.x(:,1);
sd     = T.floater.vx(:,1);

theta  = T.floater.theta(:,1);
thetad = T.floater.theta_dot(:,1);


% Sway remains unchanged in this 2-DOF model

y_disp = T.floater.y(:,1);
y_dot  = T.floater.vy(:,1);



%% Extract surge-pitch matrices

% DOF ordering:
% [surge sway heave roll pitch yaw] = [1 2 3 4 5 6]

idx = [1 5];


M2    = T.floater.MatFloat.M(idx,idx);
K2    = T.floater.MatFloat.K(idx,idx);

Cadd2 = T.floater.MatFloat.AddCLin(idx,idx);
B2    = T.floater.MatFloat.AddBLin(idx,idx);


Keff2 = K2 + Cadd2;
Beff2 = B2;



%% State-space matrices

% x = [q; qdot]

Ass = [zeros(2)       eye(2);
       -M2\Keff2     -M2\Beff2];


Bss = [zeros(2);
       M2\eye(2)];



%% Rotor area

A = pi*(T.D/2).^2;



%% Hydrodynamic quadratic drag parameters

rho_water   = 1025;      % water density [kg/m3]
Cd_surge    = 0.7;       % drag coefficient [-]

D_col       = 12.0;      % column diameter [m]
draft       = 26.5;      % draft [m]
n_col       = 4;

A_wet_total = n_col*D_col*draft;



%% Time integration parameters

dt     = Sim.TimeStep;
Nsub   = 100;
dt_sub = dt/Nsub;


idxT = T.StartI;



%% Wind speed and hub height

Ue = tmpM(:,3);

z_hub = T.posNac(:,3);



%% Allocate aerodynamic force output

Faero = zeros(T.nT,2);



%% Integrate nonlinear platform dynamics

for iT = 1:T.nT


    % Initial state

    x = [s(iT);
         theta(iT);
         sd(iT);
         thetad(iT)];


    for k = 1:Nsub


        % Current surge velocity

        surge_speed = x(3);



        % Relative wind velocity seen by rotor

        Urel = Ue(iT)-surge_speed;

        % Avoid negative relative wind speed
        Urel = max(Urel,0);



        % Nonlinear aerodynamic thrust

        FT_iT = 0.5 * paramFLORIS.airDen ...
             * A(iT) * Ct(iT) * Urel^2;



        % Project thrust according to yaw angle

        yaw_iT = deg2rad(T.States_T(idxT(iT),2));


        Faero_iT = AeroForce(FT_iT,yaw_iT);


        Faero(iT,:) = Faero_iT;



        % Surge aerodynamic force

        Fs_iT = Faero_iT(1);



        % Pitch moment generated by thrust

        Mtheta_iT = z_hub(iT)*Fs_iT;



        % Nonlinear hydrodynamic drag

        F_drag = 0.5*rho_water*Cd_surge*A_wet_total ...
               * abs(surge_speed)*surge_speed;



        % Generalized force vector

        F2 = [Fs_iT - F_drag;
              Mtheta_iT];



        % State-space integration

        xdot = Ass*x + Bss*F2;

        x = x + dt_sub*xdot;


    end



    % Store updated states

    s(iT)      = x(1);
    theta(iT)  = x(2);

    sd(iT)     = x(3);
    thetad(iT)= x(4);

end



%% Update floater states


T.floater.x(:,1)  = s;
T.floater.vx(:,1) = sd;


T.floater.y(:,1)  = y_disp;
T.floater.vy(:,1) = y_dot;


T.floater.theta(:,1)     = theta;
T.floater.theta_dot(:,1) = thetad;



%% Pitch-induced nacelle displacement

x_disp_pitch = z_hub.*sin(theta);

x_dot_pitch = (z_hub.*thetad).*cos(theta);


T.floater.pitch_ws = x_dot_pitch;



%% Update platform position

wd = T.States_WF(T.StartI,2);

alpha = mod(wd-270,360);



T.posBase(:,1) = T.pos0(:,1) ...
    +(T.floater.x(:,1)+x_disp_pitch).*cosd(alpha) ...
    -T.floater.y(:,1).*sind(alpha);



T.posBase(:,2) = T.pos0(:,2) ...
    +T.floater.y(:,1).*cosd(alpha) ...
    +(T.floater.x(:,1)+x_disp_pitch).*sind(alpha);



%% Outputs


x_disp = T.floater.x(:,1)+x_disp_pitch;

x_dot  = T.floater.vx(:,1)+x_dot_pitch;


y_disp = T.floater.y(:,1);

y_dot  = T.floater.vy(:,1);



%% Update observation point height

T.States_OP(T.StartI,3)=z_hub.*cos(theta);


end